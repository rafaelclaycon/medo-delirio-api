/// Every route the API serves, with what it returns. The apps call these exact paths,
/// so a route that disappears, moves or answers with a different type is a breaking
/// change; this list makes one show up as a test failure.
struct RoutesTests {

    @Test func `Every route keeps its path and response type`() async throws {
        try await withTestApp { app in
            let routes = app.routes.all
                .map { "\($0.description) → \(String(describing: $0.responseType))" }
                .sorted()
            #expect(routes == Self.expected)
        }
    }

    @Test func `No two routes share a method and path`() async throws {
        try await withTestApp { app in
            let paths = app.routes.all.map(\.description)
            #expect(Set(paths).count == paths.count)
        }
    }

